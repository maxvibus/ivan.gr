"""ΠΡΩΤΗ ΜΟΡΦΗ (φυλάγεται): σκίτσο για «Το να δέχεσαι ότι αγαπιέσαι» (25.11.2026).
Ιδέα: η ανάπαυση του άλλου πάνω σε εκείνον που δέχεται. Ένα ανοιχτό χέρι, με την παλάμη προς τα πάνω,
και πάνω του ένα μικρό πουλί που κοιμάται, με το κεφάλι χωμένο στα φτερά. Το χέρι δεν κλείνει και δεν δίνει τίποτα·
κρατά μόνο. Μία λεπτομέρεια: η ανάσα του πουλιού, δύο γραμμούλες. Ώχρα μόνο η ζεστασιά γύρω από το πουλί.
Χωρίς λεζάντα, όπως τα τελευταία σκίτσα."""
import os, sys, math
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pen import Pen, OCHRE

ALT = ('Ένα ανοιχτό χέρι, με την παλάμη προς τα πάνω, απλώνεται από αριστερά. '
       'Πάνω στην παλάμη κοιμάται ένα μικρό πουλί, με το κεφάλι χωμένο στα φτερά του. '
       'Το χέρι δεν κλείνει· μόνο κρατά. Γύρω από το πουλί μια απαλή ζεστασιά.')


def hide(p, pts):
    p.out.append(f'<path d="{p.smooth(pts, True)}" stroke="none" style="fill:var(--bg,#FBF8F2)"/>')


def draw(p):
    # --- αρχιτεκτονικό φόντο: ένα ψηλό παράθυρο με τόξο, αχνό ---------------------
    for x in (1010, 1130):
        p.line(p.seg(x, 120, x, 560, 10), w=1.3, op=.28)
    p.line(p.arc(1070, 120, 60, 56, math.pi, 2 * math.pi, 20), w=1.3, op=.28)
    p.line(p.seg(1070, 64, 1070, 560, 10), w=1.1, op=.22)
    p.line(p.seg(1010, 330, 1130, 330, 6), w=1.1, op=.22)
    p.line(p.seg(990, 560, 1150, 560, 6), w=1.4, op=.3)

    S, OX, OY = 1.55, -90, -300
    T = lambda pts: [(OX + x * S, OY + y * S) for x, y in pts]
    L = lambda pts, **k: p.line(T(pts), **k)
    # --- το χέρι: πήχης από κάτω αριστερά, παλάμη ανοιχτή προς τα πάνω -----------
    L([(150, 640), (200, 590), (240, 560)], w=2.2, op=.7)            # μανίκι, πάνω
    L([(210, 640), (262, 600), (300, 582)], w=2.2, op=.7)            # μανίκι, κάτω
    L([(238, 562), (270, 572), (300, 582)], w=1.8, op=.6)            # άκρη μανικιού
    L([(300, 582), (360, 560), (430, 540), (520, 522), (600, 512)], w=2.8)   # κάτω πλευρά παλάμης
    L([(240, 560), (280, 540), (320, 522)], w=2.8)                   # καρπός, πάνω
    # αντίχειρας, ανοιχτός προς τα πάνω, μπροστά από την παλάμη
    L([(320, 522), (334, 500), (352, 478), (372, 466), (386, 468), (384, 482), (366, 500), (356, 518)], w=2.6)
    # δάχτυλα: τέσσερα, ελαφρά λυγισμένα, ανοιχτά
    for (bx, by), (tx, ty), k in zip([(470, 506), (500, 508), (530, 512), (560, 516)],
                                     [(612, 482), (634, 492), (644, 504), (634, 516)], range(4)):
        L([(bx, by), ((bx + tx) / 2, min(by, ty) - 16 + k * 4), (tx, ty)], w=2.2, op=.9)
    L([(600, 512), (624, 516), (634, 516)], w=2.2, op=.9)
    L([(350, 540), (400, 530), (450, 524)], w=1.2, op=.35)          # γραμμές της παλάμης
    L([(380, 550), (430, 536)], w=1.1, op=.3)

    # --- ζεστασιά γύρω από το πουλί (ώχρα, μόνο αυτή) ------------------------------
    cx, cy = OX + 455 * S, OY + 470 * S
    p.group('sk-glow')
    for rr, op in ((120, .34), (158, .2)):
        p.line(p.arc(cx, cy, rr * S, rr * .7 * S, math.pi * 1.06, math.pi * 1.94, 20), w=1.5, op=op, col=OCHRE, a=.6)
    p.end()

    # --- το πουλί που κοιμάται --------------------------------------------------
    body = [(400, 506), (404, 474), (424, 450), (456, 438), (490, 444), (514, 462), (522, 488), (508, 506), (474, 514), (430, 514)]
    hide(p, T(body))
    L(body, w=2.8, closed=True)
    L([(430, 456), (416, 468), (414, 486), (428, 496)], w=2.2)       # το κεφάλι χωμένο στα φτερά
    L(p.arc(432, 474, 7, 4, 0, math.pi, 6), w=1.6)                   # μάτι κλειστό
    L([(420, 484), (410, 488), (420, 492)], w=1.6, op=.85)           # ράμφος
    L([(454, 456), (492, 464), (512, 486), (496, 500), (462, 502)], w=2, op=.85)   # φτερό
    L([(472, 474), (496, 484)], w=1.3, op=.55)
    L([(468, 488), (490, 494)], w=1.3, op=.55)
    L([(518, 492), (552, 500), (578, 506)], w=2, op=.85)             # ουρά πάνω στα δάχτυλα
    L([(516, 502), (546, 510), (568, 514)], w=1.6, op=.7)

    # --- η ανάσα: δύο γραμμούλες -------------------------------------------------
    p.group('sk-steam sk-st0'); L([(400, 478), (386, 472)], w=1.4, op=.55); p.end()
    p.group('sk-steam sk-st1'); L([(398, 490), (382, 490)], w=1.4, op=.45); p.end()
    return ALT


def svg():
    p = Pen(seed=sum(map(ord, 'to-na-dechesai-oti-agapiesai')))
    draw(p)
    return p.svg(ALT)


