from pen import Pen, OCHRE

ALT = ('Ένα μεγάλο χέρι υψώνεται από ακατέργαστη πέτρα, με την παλάμη ανοιχτή προς τα πάνω '
       'και τα δάχτυλα να κυρτώνουν γύρω της. Μέσα στην παλάμη κάθεται ένας άνθρωπος, '
       'με την πλάτη προς εμάς, και αγκαλιάζει τα γόνατά του. Γύρω του μια απαλή ζεστασιά.')

BG = 'var(--bg,#FBF8F2)'


def hide(p, pts):
    p.out.append(f'<path d="{p.smooth(pts, True)}" stroke="none" style="fill:{BG}"/>')


def bez(P, n=24):
    """Κυβική Bézier από τέσσερα σημεία."""
    (x0, y0), (x1, y1), (x2, y2), (x3, y3) = P
    out = []
    for i in range(n + 1):
        t = i / n; u = 1 - t
        out.append((u**3 * x0 + 3 * u * u * t * x1 + 3 * u * t * t * x2 + t**3 * x3,
                    u**3 * y0 + 3 * u * u * t * y1 + 3 * u * t * t * y2 + t**3 * y3))
    return out


def offset(c, w0, w1):
    """Δύο περιγράμματα γύρω από μια κεντρική γραμμή, με πλάτος που λεπταίνει από w0 σε w1."""
    L, R = [], []
    n = len(c)
    for i, (x, y) in enumerate(c):
        a, b = c[max(i - 1, 0)], c[min(i + 1, n - 1)]
        dx, dy = b[0] - a[0], b[1] - a[1]; d = math.hypot(dx, dy) or 1
        nx, ny = -dy / d, dx / d
        w = (w0 + (w1 - w0) * i / (n - 1)) / 2
        L.append((x + nx * w, y + ny * w)); R.append((x - nx * w, y - ny * w))
    return L, R


def finger(p, P, w0, w1, shade=True):
    """Ένα δάχτυλο: κεντρική καμπύλη P (Bézier), περιγράμματα, στρογγυλή άκρη, νύχι, δύο αρθρώσεις."""
    c = bez(P, 30)
    L, R = offset(c, w0, w1)
    tip = c[-1]
    ang = math.atan2(c[-1][1] - c[-2][1], c[-1][0] - c[-2][0])
    cap = [(tip[0] + w1 / 2 * math.cos(ang + math.pi / 2 - t * math.pi / 8),
            tip[1] + w1 / 2 * math.sin(ang + math.pi / 2 - t * math.pi / 8)) for t in range(9)]
    hide(p, L + cap + R[::-1])
    p.line(L + cap, w=2.2, a=.35)
    p.line(R, w=2.2, a=.35)
    nx0, ny0 = c[-5]                                   # νύχι
    p.line(p.arc(nx0 + math.cos(ang) * 4, ny0 + math.sin(ang) * 4, w1 * .3, w1 * .22,
                 ang + math.pi * .5, ang + math.pi * 1.5, 8), w=1.2, op=.6, a=.2)
    for f in (.36, .68):                               # αρθρώσεις
        i = int(f * (len(c) - 1))
        (lx, ly), (rx, ry), (cx, cy) = L[i], R[i], c[i]
        p.line([(lx * .8 + cx * .2, ly * .8 + cy * .2), (cx + math.cos(ang) * 3, cy + math.sin(ang) * 3),
                (rx * .7 + cx * .3, ry * .7 + cy * .3)], w=1.1, op=.5, a=.2)
    if shade:                                          # σκίαση με λεπτές γραμμές στη μία πλευρά
        for i in range(3, len(c) - 4, 3):
            (rx, ry), (cx, cy) = R[i], c[i]
            p.line([(rx, ry), (rx * .55 + cx * .45, ry * .55 + cy * .45)], w=.8, op=.35, a=.1)


def stone(p):
    """Η ακατέργαστη πέτρα από την οποία βγαίνει το χέρι."""
    top = [(400, 640), (418, 618), (436, 626), (454, 604), (480, 612), (500, 592), (526, 598), (540, 586),
           (742, 590), (764, 580), (782, 596), (806, 588), (826, 606), (846, 600), (862, 622), (880, 640)]
    hide(p, top + [(886, 700), (392, 700)])
    p.line(p.poly(top, 3), w=2.2, a=.5)
    p.line([(400, 640), (388, 672), (392, 700)], w=2, op=.85, a=.8)
    p.line([(880, 640), (892, 674), (886, 700)], w=2, op=.85, a=.8)
    p.line(p.seg(340, 702, 940, 702, 20), w=1.6, op=.6)
    r = p.r
    for gx, gy in [(420, 668), (470, 690), (510, 640), (560, 686), (620, 668), (690, 690), (740, 650),
                   (790, 684), (830, 656), (850, 692), (480, 626), (800, 628)]:
        for k in range(4):
            x = gx + k * 6 + r.uniform(-2, 2); y = gy + r.uniform(-3, 3)
            p.line([(x, y), (x + 9, y - 14)], w=.9, op=.3, a=.3)
    p.line([(620, 700), (628, 682), (622, 664), (634, 648)], w=1, op=.3, a=.6)
    p.line([(440, 700), (450, 684), (444, 670)], w=1, op=.25, a=.6)


def draw(p):
    for x in range(140, 1100, 120):                    # αχνός κάνναβος
        p.line(p.seg(x, 60, x, 700, 14), w=.8, op=.1, a=.2)
    p.line(p.arc(630, 300, 300, 260, math.pi * 1.08, math.pi * 1.92, 40), w=1.2, op=.2, a=.4)

    # Το χέρι και ο άνθρωπος σχεδιάζονται σε δικό τους σύστημα και μεγεθύνονται μαζί.
    p.out.append('<g transform="translate(-205 -215) scale(1.3)">')
    # --- καρπός που βγαίνει από την πέτρα ----------------------------------------
    p.line(bez([(562, 660), (566, 580), (572, 520), (590, 488)]), w=2.4, a=.3)
    p.line(bez([(704, 664), (704, 580), (716, 524), (744, 500)]), w=2.4, a=.3)
    for i in range(7):
        y = 596 - i * 13
        p.line([(688 + i * 1.5, y), (702 + i * 2.2, y - 7)], w=.7, op=.32, a=.1)
    p.line(bez([(598, 590), (614, 572), (646, 570), (668, 584)], 10), w=.9, op=.35, a=.2)
    p.line(bez([(604, 560), (620, 548), (650, 546), (672, 556)], 10), w=.8, op=.25, a=.2)

    # --- τα τέσσερα δάχτυλα, από τον δείκτη (πιο πίσω) ως τον μικρό (πιο μπροστά) ----
    for P, w0, w1 in [
        ([(748, 470), (798, 424), (806, 344), (770, 286)], 48, 31),
        ([(768, 480), (830, 440), (842, 360), (812, 300)], 50, 32),
        ([(784, 494), (842, 466), (858, 396), (840, 338)], 48, 30),
        ([(796, 510), (846, 502), (866, 450), (858, 404)], 42, 26),
    ]:
        finger(p, P, w0, w1)

    # --- η παλάμη: κοίλη, ανοιχτή προς τα πάνω· καλύπτει τις βάσεις των δαχτύλων ----
    front = bez([(572, 520), (616, 548), (730, 548), (812, 508)], 30)        # μπροστινό χείλος
    rim = bez([(812, 508), (790, 470), (730, 456), (600, 474)], 30)           # βάση των δαχτύλων
    hide(p, front + rim[1:])
    p.line(front, w=2.8, a=.3)
    p.line(bez([(744, 500), (770, 520), (796, 522), (812, 508)], 10), w=2.4, a=.3)   # έξω πλευρά ως τον μικρό
    p.line(bez([(752, 462), (770, 470), (790, 486), (806, 504)], 10), w=1.2, op=.55, a=.2)  # πτυχή στη βάση των δαχτύλων
    p.line(bez([(616, 500), (660, 490), (700, 490), (746, 482)], 12), w=1, op=.42, a=.2)    # γραμμές της παλάμης
    p.line(bez([(628, 514), (668, 508), (712, 508), (760, 498)], 12), w=.9, op=.3, a=.2)
    for i in range(12):
        x = 612 + i * 15
        p.line([(x, 532 - i * .8), (x + 9, 518 - i * .8)], w=.75, op=.24, a=.1)

    # --- ζεστασιά (ώχρα) ----------------------------------------------------------
    p.group('sk-glow')
    for rr, op in ((92, .36), (124, .2)):
        p.line(p.arc(684, 448, rr, rr * .9, math.pi * 1.02, math.pi * 1.98, 26), w=1.3, op=op, col=OCHRE, a=.5)
    p.end()

    # --- ο άνθρωπος, με την πλάτη προς εμάς, αγκαλιάζει τα γόνατα --------------------
    # σιλουέτα: ώμοι γερτοί και στρογγεμένοι, πλάτη που φαρδαίνει προς το κάθισμα
    L_ = bez([(654, 510), (650, 498), (649, 484), (648, 470)], 8) + bez([(648, 470), (640, 458), (636, 440), (646, 428)], 10)[1:] + \
        bez([(646, 428), (654, 420), (664, 418), (672, 420)], 6)[1:]
    R_ = bez([(696, 420), (704, 418), (714, 420), (722, 428)], 6) + bez([(722, 428), (732, 440), (728, 458), (720, 470)], 10)[1:] + \
        bez([(720, 470), (719, 484), (718, 498), (714, 510)], 8)[1:]
    hide(p, L_ + R_ + [(684, 516)])
    p.line(L_, w=2.3, a=.15)
    p.line(R_, w=2.3, a=.15)
    p.line(bez([(652, 510), (668, 518), (700, 518), (716, 510)], 10), w=2, op=.85, a=.12)  # κάθισμα στην παλάμη
    # τα μπράτσα κατεβαίνουν μπροστά προς τα γόνατα· στο πλάι φαίνεται μόνο η καμπύλη τους
    p.line(bez([(650, 432), (646, 446), (648, 460), (656, 468)], 10), w=1.3, op=.6, a=.1)
    p.line(bez([(718, 432), (722, 446), (720, 460), (712, 468)], 10), w=1.3, op=.6, a=.1)
    for i in range(7):                                   # σκιά στη δεξιά πλευρά της πλάτης
        y = 446 + i * 8
        p.line([(718 - i * .2, y), (724 - i * .2, y + 6)], w=.7, op=.35, a=.1)
    p.line(bez([(684, 430), (683, 456), (683, 480), (684, 504)], 8), w=.7, op=.25, a=.1)   # αχνή σπονδυλική στήλη
    # κεφάλι σκυμμένο, χαμηλωμένο ανάμεσα στους ώμους
    head = p.arc(684, 410, 13, 14, 0, 2 * math.pi, 22)
    hide(p, head)
    p.line(head, w=2.1, closed=True, a=.12)
    p.line(bez([(672, 402), (678, 396), (690, 396), (696, 402)], 8), w=.9, op=.5, a=.1)    # μαλλιά
    p.line(bez([(672, 416), (676, 420), (692, 420), (696, 416)], 6), w=1.2, op=.7, a=.1)   # ώμοι που ανεβαίνουν γύρω από τον σβέρκο

    # --- ο αντίχειρας, μπροστά αριστερά, ανοιχτός ------------------------------------
    finger(p, [(612, 506), (566, 500), (544, 464), (566, 428)], 50, 32, shade=False)
    p.line(bez([(590, 488), (594, 504), (604, 518), (618, 526)], 8), w=1.4, op=.5, a=.2)   # θέναρ
    p.out.append('</g>')
    stone(p)
    return ALT


def svg():
    p = Pen(seed=sum(map(ord, 'to-na-dechesai-oti-agapiesai')))
    draw(p)
    return p.svg(ALT)


