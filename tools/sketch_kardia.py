"""Σκίτσο για «Μου απαντούν όσοι έχουν καρδιά, όχι χαρτιά» (18.11.2026, δεύτερη μορφή).
Αριστερά: ένα γκισέ με τζάμι και πινακίδα «ΠΑΡΑΚΑΛΩ ΠΕΡΙΜΕΝΕΤΕ», ο αριθμός προτεραιότητας κολλημένος,
η καρέκλα πίσω από το τζάμι άδεια· μπροστά, στον πάγκο, ένα βουνό φάκελοι κλειστοί σαν σφιγμένα στόματα.
Δεξιά: ένας χαμηλός φράχτης κι ένα σπίτι απέναντι με αναμμένο παράθυρο· από εκεί ένα χάρτινο αεροπλανάκι
(ώχρα) έρχεται προς τα εδώ. Η απάντηση ήρθε από απέναντι."""
import os, sys, math
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pen import Pen, OCHRE

ALT = ('Αριστερά, ένα γκισέ με τζάμι και πινακίδα «Παρακαλώ περιμένετε»· η καρέκλα πίσω από το τζάμι είναι άδεια '
       'και μπροστά, στον πάγκο, στοιβάζονται κλειστοί φάκελοι σαν σφιγμένα στόματα. '
       'Δεξιά, πίσω από έναν χαμηλό φράχτη, ένα σπίτι απέναντι με αναμμένο παράθυρο, από όπου έρχεται ένα χάρτινο αεροπλανάκι.')


def draw(p):
    r = p.r
    fy = 610
    p.floor(fy, 40, 1160)
    # --- το γκισέ ------------------------------------------------------------
    gx0, gx1 = 70, 600
    for x in range(gx0, gx1 + 1, 53):                          # πλακάκια τοίχου, αχνά
        p.line(p.seg(x, 120, x, 420, 6), w=1.1, op=.2)
    for y in range(120, 421, 50):
        p.line(p.seg(gx0, y, gx1, y, 8), w=1.1, op=.2)
    # πινακίδα
    p.line(p.poly([(150, 92), (520, 92), (520, 136), (150, 136), (150, 92)], 6), w=2.2)
    p.text(335, 122, 'ΠΑΡΑΚΑΛΩ ΠΕΡΙΜΕΝΕΤΕ', size=22, italic=False, anchor='middle', spacing=3)
    # ο αριθμός προτεραιότητας, σταματημένος
    p.line(p.poly([(530, 160), (590, 160), (590, 200), (530, 200), (530, 160)], 3), w=1.8)
    p.text(560, 189, '047', size=24, italic=False, anchor='middle', spacing=1)
    # το τζάμι και η τρύπα για τη φωνή
    p.line(p.poly([(160, 170), (500, 170), (500, 420), (160, 420), (160, 170)], 6), w=2.6)
    for k in range(3):                                         # αντανάκλαση
        p.line(p.seg(190 + k * 18, 196, 250 + k * 18, 270, 4), w=1.2, op=.3)
    p.ring(300, 250, 22, 16, w=1.6, op=.7)
    for k in range(-2, 3):
        p.line(p.seg(300 + k * 7, 240, 300 + k * 7, 260, 2), w=1.0, op=.5)
    # η άδεια καρέκλα πίσω από το τζάμι
    p.line(p.poly([(380, 300), (384, 220), (440, 218), (444, 300)], 4), w=1.6, op=.55)
    p.line(p.seg(372, 300, 452, 300, 4), w=1.6, op=.55)
    p.line([(380, 300), (378, 360)], w=1.4, op=.45); p.line([(446, 300), (448, 360)], w=1.4, op=.45)
    # ο πάγκος
    p.line(p.seg(40, 420, 630, 420, 12), w=2.8)
    p.line(p.seg(40, 436, 630, 436, 12), w=1.6, op=.7)
    p.line(p.seg(60, 436, 60, fy, 6), w=1.6, op=.6); p.line(p.seg(610, 436, 610, fy, 6), w=1.6, op=.6)
    # οι φάκελοι: κλειστοί, σαν σφιγμένα στόματα
    for row, (n, y) in enumerate(((7, 406), (6, 380), (5, 354), (3, 328))):
        for i in range(n):
            ex = 90 + row * 30 + i * 64 + r.uniform(-4, 4)
            ey = y + r.uniform(-2, 2)
            w, h = 58, 24
            p.line(p.poly([(ex, ey), (ex + w, ey), (ex + w, ey - h), (ex, ey - h), (ex, ey)], 3), w=1.6, op=.75)
            # το καπάκι: μια σφιγμένη γραμμή-στόμα
            p.line([(ex + 6, ey - h + 4), (ex + w / 2, ey - h + 12), (ex + w - 6, ey - h + 4)], w=1.4, op=.75)
            p.line(p.seg(ex + w / 2 - 9, ey - 8, ex + w / 2 + 9, ey - 8, 2), w=1.8, op=.8)
    # --- απέναντι: φράχτης, σπίτι, αναμμένο παράθυρο ---------------------------
    for xx in range(700, 1170, 24):
        p.line(p.seg(xx, fy, xx, fy - 96 - r.uniform(-4, 4), 3), w=1.3, op=.4)
    p.line(p.seg(700, fy - 80, 1160, fy - 80, 10), w=1.3, op=.4)
    hx0, hx1, hy0 = 850, 1100, 330
    p.line(p.poly([(hx0, fy - 96), (hx0, hy0), (975, hy0 - 90), (hx1, hy0), (hx1, fy - 96)], 6), w=2.0, op=.7)
    p.line(p.poly([(1040, hy0 - 40), (1040, hy0 - 84), (1064, hy0 - 84), (1064, hy0 - 22)], 3), w=1.6, op=.6)   # καμινάδα
    p.group('sk-glow')
    p.line(p.poly([(900, 380), (960, 380), (960, 440), (900, 440), (900, 380)], 3), w=2.2, col=OCHRE)
    p.line(p.seg(930, 380, 930, 440, 3), w=1.4, col=OCHRE); p.line(p.seg(900, 410, 960, 410, 3), w=1.4, col=OCHRE)
    p.end()
    # --- το χάρτινο αεροπλανάκι, από απέναντι προς τα εδώ ---------------------
    ax, ay = 700, 250
    p.group('sk-glow')
    p.line(p.poly([(ax, ay), (ax + 74, ay - 18), (ax + 58, ay + 12), (ax, ay)], 4), w=2.2, col=OCHRE, a=.4)
    p.line(p.poly([(ax, ay), (ax + 46, ay + 26), (ax + 58, ay + 12)], 4), w=1.8, col=OCHRE, a=.4)
    p.line(p.seg(ax, ay, ax + 74, ay - 18, 4), w=1.2, col=OCHRE, a=.3)
    p.end()
    p.line([(ax + 84, ay + 4), (ax + 140, ay + 30), (ax + 190, ay + 80), (ax + 210, ay + 128)], w=1.2, op=.3, a=.6)   # η διαδρομή του
    for i in range(2):
        p.line(p.seg(ax + 86, ay + 2 + i * 14, ax + 118, ay + 8 + i * 14, 3), w=1.3, op=.5)
    return ALT


def svg():
    p = Pen(seed=sum(map(ord, 'kardia-ochi-chartia')))
    draw(p)
    return p.svg(ALT)


if __name__ == '__main__':
    out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'assets', 'sketches', 'kardia-ochi-chartia.svg')
    open(out, 'w', encoding='utf-8').write(svg()); print(out)
